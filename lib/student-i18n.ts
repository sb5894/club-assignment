export function studentText(text: string, language: StudentLanguage) {
  return language === 'ru' ? (studentRussian[text] ?? text) : text;
}

export function studentError(message: string, language: StudentLanguage) {
  if (language === 'ko') return message;
  return (
    studentRussian[message] ?? studentRussian['잠시 후 다시 시도해 주세요.']
  );
}

export function preferenceLabel(rank: number, language: StudentLanguage) {
  return language === 'ru' ? `${rank}-е место` : `${rank}지망`;
}

export function studentDate(value: string | null, language: StudentLanguage) {
  return value
    ? new Date(value).toLocaleString(language === 'ru' ? 'ru-RU' : 'ko-KR', {
        timeZone: 'Asia/Seoul',
      })
    : '';
}
